import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await build({ absWorkingDir: root, entryPoints: ['lib/four-point-game.ts'], outfile: 'public/four-point-game-runtime.js',
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: false,
  banner: { js: '// Generated by node scripts/build-four-point-game.mjs. Real front-source endpoints; display-only guides.' } });
console.log('Built public/four-point-game-runtime.js.');
