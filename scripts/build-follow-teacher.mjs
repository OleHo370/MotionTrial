import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await build({
  absWorkingDir: root, entryPoints: ['lib/follow-teacher.ts'], outfile: 'public/follow-teacher-runtime.js',
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: false,
  banner: { js: '// Generated by node scripts/build-follow-teacher.mjs. Local pinned MediaPipe and unchanged practice helpers.' },
});
console.log('Built public/follow-teacher-runtime.js from local dependencies.');
